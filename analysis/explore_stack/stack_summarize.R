#!/usr/bin/env Rscript
# EXPLORATORY (docs/plans/explore_stack_plan.md sections 4, 6, 8). Tables, contrasts and the literal pass/fail from the readout caches of
# stack_k562.R / stack_m3d.R. No p-values. Usage: Rscript analysis/explore_stack/stack_summarize.R results/explore_stack/k562 [results/explore_stack/m3d ...]
dirs <- commandArgs(TRUE)
RO <- c("K10", "CLR", "a3r", "a3r2", "a3r3", "a3r2_t2_2", "a3r2_t2_4", "c1_t18", "c1_t27", "c2_z", "c2_log")
VS <- c("a3r", "K10", "CLR", "c1_t18", "c1_t27")
SCOPES <- c(raw = "raw", hub_mi = "hub_mi", hub_att = "hub_pi")
f4 <- function(x) sprintf("%+.4f", x); ci <- function(d, lo, hi) sprintf("%+.4f [%+.4f, %+.4f]", d, lo, hi)
for (out in dirs) {
  ds <- basename(out); cache <- file.path(out, "cache"); meta <- readRDS(file.path(cache, "meta.rds")); br <- meta$base_rate; TR <- meta$truths
  R <- stats::setNames(lapply(RO, function(n) readRDS(file.path(cache, paste0("readout__", n, ".rds")))), RO)
  lev <- do.call(rbind, lapply(RO, function(r) do.call(rbind, lapply(names(SCOPES), function(sc) data.frame(readout = r, scope = sc, truth = TR,
    aupr = vapply(TR, function(e) R[[r]][[sc]][[e]]$aupr, 0), base_rate = br[TR], row.names = NULL)))))
  lev$enrichment <- lev$aupr / lev$base_rate; utils::write.csv(lev, file.path(out, "pooled_levels.csv"), row.names = FALSE)
  contr <- function(x, v, sc, e) { d <- R[[x]][[sc]][[e]]$aupr - R[[v]][[sc]][[e]]$aupr; s <- stats::sd(R[[x]][[sc]][[e]]$jack - R[[v]][[sc]][[e]]$jack)
    list(d = d, lo = d - 1.96 * s, hi = d + 1.96 * s) }
  con <- do.call(rbind, lapply(RO, function(x) do.call(rbind, lapply(setdiff(VS, x), function(v) do.call(rbind, lapply(names(SCOPES), function(sc) do.call(rbind, lapply(TR, function(e) {
    z <- contr(x, v, sc, e); data.frame(readout = x, versus = v, scope = sc, truth = e, d_aupr = z$d, lo_aupr = z$lo, hi_aupr = z$hi,
      d_enr = z$d / br[[e]], lo_enr = z$lo / br[[e]], hi_enr = z$hi / br[[e]], row.names = NULL) }))))))))
  utils::write.csv(con, file.path(out, "contrasts.csv"), row.names = FALSE)
  ## ---- literal pass rule ------------------------------------------------------------------------------------------------------
  pf <- NULL; stack <- list(a3r2 = list(N = 2L, c1 = "c1_t18"), a3r3 = list(N = 3L, c1 = "c1_t27"))
  if ("CORUM_all" %in% TR) {
    row1 <- function(x, c1, variant, sc13, sc4) {
      u <- contr(x, "a3r", sc13, "CORUM_all"); cd <- contr(x, "a3r", sc13, "DoRothEA_AB"); ct <- contr(x, "a3r", sc13, "CollecTRI")
      m <- contr(x, c1, sc13, "CORUM_all"); h <- contr(x, "a3r", sc4, "CORUM_all")
      c1ok <- u$d >= 0.005 && u$lo > 0; c2ok <- cd$d >= -0.005 && ct$d >= -0.005; c3ok <- m$d >= 0.005 && m$lo > 0; c4ok <- h$d > 0
      data.frame(dataset = ds, readout = x, layers = stack[[x]]$N, variant = variant, matched_control = c1,
        cond1_corum_vs_a3r = f4(u$d), cond1_lo = f4(u$lo), cond1_ok = c1ok, cond2_dorothea = f4(cd$d), cond2_collectri = f4(ct$d), cond2_ok = c2ok,
        cond3_corum_vs_c1 = f4(m$d), cond3_lo = f4(m$lo), cond3_ok = c3ok, cond4_hub_corum_vs_a3r = f4(h$d), cond4_ok = c4ok,
        pass = c1ok && c2ok && c3ok && c4ok, row.names = NULL) }
    pf <- do.call(rbind, lapply(names(stack), function(x) rbind(
      row1(x, stack[[x]]$c1, "MI (primary): cond 1-3 raw, cond 4 hub MI", "raw", "hub_mi"),
      row1(x, stack[[x]]$c1, "pi (sensitivity): cond 1-3 raw, cond 4 hub pi", "raw", "hub_att"),
      row1(x, stack[[x]]$c1, "strict MI: cond 1-3 and 4 on hub-MI scores", "hub_mi", "hub_mi"),
      row1(x, stack[[x]]$c1, "strict pi: cond 1-3 and 4 on hub-pi scores", "hub_att", "hub_att"))))
  } else {
    row1 <- function(x, variant, sc) {
      s <- contr(x, "a3r", sc, "regulons_SC"); a <- contr(x, "a3r", sc, "regulons_all"); k <- contr(x, "a3r", sc, "complexes")
      ok1 <- s$lo >= -0.005; ok2 <- a$lo >= -0.005; ok3 <- k$d >= 0
      data.frame(dataset = ds, readout = x, layers = stack[[x]]$N, variant = variant,
        SC_d = f4(s$d), SC_lo = f4(s$lo), SC_noninf = ok1, all_d = f4(a$d), all_lo = f4(a$lo), all_noninf = ok2, complexes_d = f4(k$d), complexes_not_decreased = ok3,
        pass = ok1 && ok2 && ok3, row.names = NULL) }
    pf <- do.call(rbind, lapply(names(stack), function(x) rbind(row1(x, "raw", "raw"), row1(x, "hub MI (primary stratifier)", "hub_mi"), row1(x, "hub pi (sensitivity)", "hub_att"))))
  }
  utils::write.csv(pf, file.path(out, "pass_fail.csv"), row.names = FALSE)
  ## ---- markdown ---------------------------------------------------------------------------------------------------------------
  md <- c(sprintf("# Stacked a3r layers, %s: tables (generated by stack_summarize.R)", toupper(ds)), "",
          "Exploratory, in-sample, descriptive intervals (paired delete-half gene jackknife, d +/- 1.96 SD); no p-values.", "",
          "## Literal pass / fail (plan section 6)", "")
  tab <- function(df) c(paste0("| ", paste(names(df), collapse = " | "), " |"), paste0("|", paste(rep("---", ncol(df)), collapse = "|"), "|"),
                        apply(df, 1, function(r) paste0("| ", paste(r, collapse = " | "), " |")))
  md <- c(md, tab(as.data.frame(lapply(pf, as.character))), "")
  for (sc in names(SCOPES)) {
    md <- c(md, sprintf("## Levels, scope %s: AUPR (enrichment)", SCOPES[[sc]]), "")
    df <- data.frame(readout = RO, do.call(cbind, lapply(TR, function(e) vapply(RO, function(r) { z <- lev[lev$readout == r & lev$scope == sc & lev$truth == e, ]; sprintf("%.4f (%.3f)", z$aupr, z$enrichment) }, ""))), row.names = NULL)
    names(df) <- c("readout", TR); md <- c(md, tab(df), "")
  }
  for (sc in names(SCOPES)) for (v in c("a3r", "K10", "CLR")) {
    md <- c(md, sprintf("## Contrast readout minus %s, scope %s: AUPR d [95%% interval]", v, SCOPES[[sc]]), "")
    xs <- setdiff(RO, v)
    df <- data.frame(readout = xs, do.call(cbind, lapply(TR, function(e) vapply(xs, function(x) { z <- con[con$readout == x & con$versus == v & con$scope == sc & con$truth == e, ]; ci(z$d_aupr, z$lo_aupr, z$hi_aupr) }, ""))), row.names = NULL)
    names(df) <- c("readout", TR); md <- c(md, tab(df), "")
  }
  md <- c(md, "## Stacked readouts minus the matched-depth control (a3r2 - c1_t18, a3r3 - c1_t27), AUPR d [95% interval]", "")
  for (sc in names(SCOPES)) { df <- do.call(rbind, lapply(names(stack), function(x) { c1 <- stack[[x]]$c1
      data.frame(scope = SCOPES[[sc]], contrast = paste(x, "-", c1), t(vapply(TR, function(e) { z <- con[con$readout == x & con$versus == c1 & con$scope == sc & con$truth == e, ]; ci(z$d_aupr, z$lo_aupr, z$hi_aupr) }, "")), row.names = NULL) }))
    names(df) <- c("scope", "contrast", TR); md <- c(md, tab(df), "") }
  dg <- file.path(out, "diagnostics_layers.csv")
  if (file.exists(dg)) { d <- utils::read.csv(dg); md <- c(md, "## Layer diagnostics (label-free; layers 4 and 5 not scored)", "", tab(as.data.frame(lapply(d, function(x) if (is.numeric(x)) signif(x, 4) else x))), "") }
  for (f in c("diagnostics_t2_grid.csv", "diagnostics_c1_depth.csv")) { p <- file.path(out, f)
    if (file.exists(p)) { d <- utils::read.csv(p); md <- c(md, paste("##", sub("\\.csv$", "", f)), "", tab(as.data.frame(lapply(d, function(x) if (is.numeric(x)) signif(x, 4) else x))), "") } }
  writeLines(md, file.path(out, "tables.md")); cat("wrote", file.path(out, "tables.md"), "\n"); print(pf, row.names = FALSE)
}
